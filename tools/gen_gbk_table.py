#!/usr/bin/env python3
"""Generate src/gbk_table.h: a self-contained GBK -> Unicode BMP lookup table.

The HiPDA forum serves text/html; charset=GBK (verified 2026-11-15). Kindle
firmware does not reliably ship gconv modules, so we embed the mapping rather
than depending on iconv at runtime. Invalid/undecodeable byte pairs map to 0.

Table index: (lead - 0x81) * 191 + (trail - 0x40)
    lead  : 0x81 .. 0xFE  (126 values)
    trail : 0x40 .. 0xFE  (191 values, 0x7F is invalid)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DST = os.path.join(ROOT, "src", "gbk_table.h")
LEAD_MIN, LEAD_MAX = 0x81, 0xFE
TRAIL_MIN, TRAIL_MAX = 0x40, 0xFE
TRAIL_SPAN = TRAIL_MAX - TRAIL_MIN + 1
LEAD_SPAN = LEAD_MAX - LEAD_MIN + 1


def main() -> int:
    table = [0] * (LEAD_SPAN * TRAIL_SPAN)
    hits = 0
    for lead in range(LEAD_MIN, LEAD_MAX + 1):
        for trail in range(TRAIL_MIN, TRAIL_MAX + 1):
            try:
                s = bytes((lead, trail)).decode("gbk")
            except UnicodeDecodeError:
                continue
            if len(s) != 1:
                continue
            cp = ord(s)
            if cp > 0xFFFF:
                continue
            table[(lead - LEAD_MIN) * TRAIL_SPAN + (trail - TRAIL_MIN)] = cp
            hits += 1

    with open(DST, "w", encoding="ascii", newline="\n") as out:
        out.write("/* Generated by tools/gen_gbk_table.py -- do not edit. */\n")
        out.write("/* GBK double-byte -> Unicode BMP. 0 = unmapped. */\n")
        out.write("#ifndef HIPDA_GBK_TABLE_H\n#define HIPDA_GBK_TABLE_H\n")
        out.write("#include <stdint.h>\n")
        out.write("#define GBK_LEAD_MIN 0x%02X\n" % LEAD_MIN)
        out.write("#define GBK_LEAD_MAX 0x%02X\n" % LEAD_MAX)
        out.write("#define GBK_TRAIL_MIN 0x%02X\n" % TRAIL_MIN)
        out.write("#define GBK_TRAIL_MAX 0x%02X\n" % TRAIL_MAX)
        out.write("#define GBK_TRAIL_SPAN %d\n" % TRAIL_SPAN)
        out.write("static const uint16_t gbk_to_uni[%d] = {\n" % len(table))
        for i in range(0, len(table), 12):
            out.write("    " + ",".join("0x%04X" % v for v in table[i:i + 12]) + ",\n")
        out.write("};\n#endif /* HIPDA_GBK_TABLE_H */\n")

    print("wrote %s: %d entries, %d mapped" % (DST, len(table), hits))
    # sanity: GBK bytes for a few common characters
    for ch in ("中", "文", "论", "坛", "帖", "的"):
        b = ch.encode("gbk")
        idx = (b[0] - LEAD_MIN) * TRAIL_SPAN + (b[1] - TRAIL_MIN)
        assert table[idx] == ord(ch), ch
    print("sanity: 中文论坛帖的 all map back correctly")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
