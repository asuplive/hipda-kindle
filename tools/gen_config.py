#!/usr/bin/env python3
"""Generate config.ini for hipda-kindle.

Discuz! 7.2's login form runs pwmd5() in JavaScript, i.e. it POSTs
MD5(password) instead of the plaintext. This tool writes only the digest.

Usage:
  python tools/gen_config.py --user MYNAME --out kual/hipda/config.ini
  (password is read from the HIPDA_PASSWORD environment variable, or typed
   interactively with getpass so it never lands in shell history)

  python tools/gen_config.py --md5-only MYPASSWORD    # just print the digest
"""
import argparse
import getpass
import hashlib
import os
import sys

TEMPLATE = """# Generated by tools/gen_config.py -- no plaintext password is stored.
forum_server={server}
image_host=https://img02.4d4y.com
username={user}
password_md5={md5}

cookie_file=/mnt/us/extensions/hipda/cookies.txt
font_file=/mnt/us/extensions/hipda/fonts/unifont.bin
cache_dir=/mnt/us/extensions/hipda/cache

net_cmd=curl
user_agent=Mozilla/5.0 (compatible; HiPDA-Kindle/0.9)
font_scale=0
full_refresh_every=6
timeout=20
forums=2,6,7,59,9,60,56,22,50,24,23,25
offline=0
no_login=0
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default="")
    ap.add_argument("--server", default="https://www.4d4y.com")
    ap.add_argument("--out", default="")
    ap.add_argument("--md5-only", metavar="PASSWORD", default=None)
    args = ap.parse_args()

    if args.md5_only is not None:
        print(hashlib.md5(args.md5_only.encode("utf-8")).hexdigest())
        return 0

    user = args.user or input("forum username: ").strip()
    pwd = os.environ.get("HIPDA_PASSWORD")
    if pwd is None:
        pwd = getpass.getpass("forum password (not echoed, not stored): ")
    if not user or not pwd:
        print("username and password are required", file=sys.stderr)
        return 2
    digest = hashlib.md5(pwd.encode("utf-8")).hexdigest()
    text = TEMPLATE.format(server=args.server, user=user, md5=digest)

    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        try:
            os.chmod(args.out, 0o600)
        except OSError:
            pass
        print("wrote %s (mode 600 where supported)" % args.out)
        print("username=%s  password_md5=%s" % (user, digest))
        print("Copy the file to /mnt/us/extensions/hipda/config.ini on the Kindle.")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
