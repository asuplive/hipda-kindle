#!/usr/bin/env python3
"""Generate src/pinyin_table.h: pinyin -> candidate characters for the
on-device Chinese input. Candidates are ordered by GB2312 level-1 order
(area 16-55), which approximates usage frequency well enough for search."""
import io, os
from pypinyin import pinyin, Style

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# GB2312 level-1: rows 0xB0..0xD7 (16..55), 94 chars per row
chars = []
for row in range(0xB0, 0xD8):
    for col in range(0xA1, 0xFF):
        try:
            ch = bytes([row, col]).decode('gb2312')
            chars.append(ch)
        except UnicodeDecodeError:
            pass
print('level-1 chars:', len(chars))

table = {}   # pinyin -> [char, ...] in GB2312 order
for ch in chars:
    py = pinyin(ch, style=Style.NORMAL, heteronym=False)[0][0]
    table.setdefault(py, []).append(ch)

keys = sorted(table.keys())
print('syllables:', len(keys))

lines = []
for k in keys:
    cs = ''.join(table[k])
    lines.append('    {"%s", "%s"},' % (k, cs))

out = io.open(os.path.join(ROOT, 'src', 'pinyin_table.h'), 'w', encoding='utf-8')
out.write('''/* Generated by tools/gen_pinyin.py -- pinyin -> candidates for the Chinese
 * input page (search only). Order follows GB2312 level-1 (rough frequency).
 * Do not edit by hand; regenerate instead. */
#ifndef HIPDA_PINYIN_TABLE_H
#define HIPDA_PINYIN_TABLE_H

typedef struct {
    const char *py;      /* tone-less full pinyin */
    const char *chars;   /* candidate UTF-8 characters, best first */
} PinyinEntry;

static const PinyinEntry kPinyin[] = {
%s
};
#define PINYIN_N ((int)(sizeof(kPinyin) / sizeof(kPinyin[0])))

#endif /* HIPDA_PINYIN_TABLE_H */
''' % '\n'.join(lines))
out.close()
print('wrote src/pinyin_table.h')
